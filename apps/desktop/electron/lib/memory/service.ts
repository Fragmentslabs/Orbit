let syncTimer: NodeJS.Timeout | null = null
let syncRunning: Promise<unknown> | null = null

/**
 * Background reindexing. A short debounce so a burst of /init saves does not
 * trigger one pass per memory, and never in series with the response.
 */
export function scheduleIndexSync(delayMs = 2_000): void {
  if (syncTimer) clearTimeout(syncTimer)
  syncTimer = setTimeout(() => {
    syncTimer = null
    void syncMemoryIndex()
  }, delayMs)
  syncTimer.unref?.()
}

/** Syncs the embedding index with the pool (idempotent). */
export async function syncMemoryIndex(): Promise<{ indexed: number; pending: number; ok: boolean }> {
  if (syncRunning) {
    await syncRunning.catch(() => {})
  }
  const run = (async () => {
    const pool = (await alive()).filter((m) => !m.proposed)
    const result = await syncIndex(pool)
    return { indexed: result.indexed, pending: 0, ok: !result.failed }
  })()
  syncRunning = run.catch(() => {})
  try {
    return await run
  } catch (err) {
    console.error('[memory] index sync failed:', err)
    return { indexed: 0, pending: 0, ok: false }
  } finally {
    syncRunning = null
  }
}

/**
 * Pool eligible for retrieval by context, per mode.
 *
 * `core` stays OUT on purpose: permanent memory already enters the fixed block of the
 * prompt, and retrieving it again would only burn tokens and duplicate the same line.
 */
export async function retrievalPool(mode: 'chat' | 'code', directory?: string): Promise<Memory[]> {
  // A proposal is not retrievable: it waits for review on the memories screen.
  const pool = (await alive()).filter((m) => !m.proposed)
  if (mode === 'chat') {
    return pool.filter((m) => (m.kind === 'seasonal' || m.kind === 'general') && visibleIn(m, 'chat'))
  }
  const scope = directory ? await resolveProjectScope(directory) : undefined
  const projectId = scope?.projectId
  return pool.filter(
    (m) =>
      visibleIn(m, 'code') &&
      (m.kind === 'general' || (m.kind === 'project' && m.projectId === projectId)),
  )
}

/**
 * Memory suggestions for the turn — on by default, id + metadata only.
 *
 * The 24/10 validation rejected TEXT injection: 84% precision on the tuning
 * fixture (target: 98% with a 95% CI lower bound >= 90%), 10/10 on the held-out set
 * with CI [72%; 100%], and the pointer level gave 0/8 useful — similarity
 * does not separate "this will help" from "this is about the same subject".
 *
 * The suggestion does not repeat that mistake because it asserts nothing: it sends the id and the
 * framing (`general/preferences`) and leaves the content one memory_open
 * away. A wrong guess costs an ignored line, not a contaminated
 * answer. And what is already in the fixed prompt block is excluded here — the
 * two paths do not tell the same story twice.
 *
 * Can be turned off with ORBIT_MEMORY_SUGGEST=0.
 */
export const MEMORY_SUGGESTIONS_ENABLED = process.env.ORBIT_MEMORY_SUGGEST !== '0'

/** Turn suggestions. Never throws (see suggestMemories). */
export async function retrieveForTurn(input: {
  text: string
  mode: 'chat' | 'code'
  directory?: string
  recent?: Array<{ role: 'user' | 'assistant'; text: string }>
  /** Ids already present in this session's system prompt block. */
  exclude?: readonly string[]
}): Promise<MemorySuggestion[]> {
  if (!MEMORY_SUGGESTIONS_ENABLED) return []
  try {
    const pool = await retrievalPool(input.mode, input.directory)
    return await suggestMemories({
      message: input.text,
      recent: input.recent,
      pool,
      docs: await docsFor(pool),
      exclude: input.exclude,
    })
  } catch (err) {
    console.error('[memory] turn suggestions failed:', err)
    return []
  }
}
