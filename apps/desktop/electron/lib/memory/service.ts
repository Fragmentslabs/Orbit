/**
 * Use cases for the Brain memory. Agent tools, the UI's IPC and prompt
 * injection talk only to this module. Every mutation emits a MemoryEvent on the
 * emitter — main.ts forwards it to the renderer on the "memory:event" channel.
 */

export const memoryEvents = new EventEmitter()

function emit(action: MemoryEvent['action'], memory: Memory) {
  memoryEvents.emit('event', { action, memory } satisfies MemoryEvent)
  // Any mutation may invalidate that memory's vector: the embedding index is
  // synced in the background, with a debounce, and never on the
  // path of the response.
  scheduleIndexSync()
}

function newId() {
  return `mem_${Date.now().toString(36)}${Math.random().toString(36).slice(2, 10)}`
}

function clampWeight(weight: number): number {
  return Math.min(1, Math.max(0, weight))
}

function normalizeTags(tags: string[] | undefined): string[] {
  const seen = new Set<string>()
  for (const tag of tags ?? []) {
    const t = tag.trim().toLowerCase()
    if (t) seen.add(t)
  }
  return [...seen].slice(0, 8)
}

async function alive(): Promise<Memory[]> {
  const now = Date.now()
  return (await repo.getIndex()).filter((m) => !isExpired(m, now))
}

/**
 * Re-saving the same memory does not move the scope: only `both` widens it. Otherwise it holds
 * where it was born, even when the second write comes from the other mode.
 */
function mergeScope(existing: Memory, incoming: MemoryScope): MemoryScope {
  const current = scopeOf(existing)
  return current === 'both' || incoming === 'both' ? 'both' : current
}

export interface SaveMemoryInput {
  text: string
  kind: MemoryKind
  /**
   * Where the memory holds. Absent = the kind's default (defaultScopeOf). Each tool
   * passes the mode it is running in as the default, and the agent only writes `both`
   * when it decides, at save time, that the fact crosses both modes.
   */
  scope?: MemoryScope
  weight?: number
  tags?: string[]
  /** Attached markdown (memory/docs/<id>.md) — for extensive context */
  document?: string
  /** Required when kind === "project". Kind "general" only accepts "learning". */
  category?: ProjectCategory
  /** Knowledge area (memories generated by /init) */
  area?: ProjectArea
  /**
   * Session folder. Required when kind === "project" (the projectId is derived
   * from it) and used in the other kinds to record the ORIGIN project — which
   * anchors the memory near the right tree on the canvas.
   */
  directory?: string
  /** Subproject within the project (e.g. "front", "back") — only when kind === "project" */
  subproject?: string
  sessionId?: string
  /**
   * Enrichment for search (optional, filled in by whoever writes).
   * `text` remains the source of truth: these fields only help
   * retrieval and must never contain a fact the text does not have.
   */
  title?: string
  summary?: string
  entities?: string[]
  keywords?: string[]
  concepts?: string[]
  /** Ids of related memories (creates links) */
  relatedIds?: string[]
  /** Relation type per target id. "parent" = hierarchy, "related" = free connection */
  relatedTypes?: Record<string, RelationType>
  /**
   * Default true: identical text or nearly equal tags merge into the existing
   * memory. /init turns it off: it has already decided, node by node, what to update and what
   * to create — and two sibling nodes with similar tags ("frontend", "react")
   * would be merged into one, making a whole branch of the tree disappear.
   */
  dedup?: boolean
  /**
   * Only the memory routine uses it: the memory starts as a proposal, outside the prompt,
   * the search and retrieval, until the user accepts it on the memories screen.
   */
  proposed?: boolean
}

export interface SaveMemoryResult {
  id: string
  merged: boolean
  /** Text of the resulting memory (the existing one, when merged) */
  text: string
}

const JACCARD_THRESHOLD = 0.85

type EnrichmentInput = Pick<SaveMemoryInput, "title" | "summary" | "entities" | "keywords" | "concepts">

/**
 * Derived fields that come with the memory. A field that is not sent stays as
 * it is: on merge — and on revise — the old enrichment is not erased.
 */
function enrichmentOf(input: EnrichmentInput): Partial<Memory> {
  const list = (items?: string[]) => {
    const clean = (items ?? []).map((s) => s.trim()).filter(Boolean).slice(0, 12)
    return clean.length ? clean : undefined
  }
  // Missing keys stay MISSING, not `undefined`: spreading `undefined`
  // over an existing memory would erase the enrichment that was already there.
  const out: Partial<Memory> = {}
  const title = input.title?.trim()
  if (title) out.title = title
  const summary = input.summary?.trim()
  if (summary) out.summary = summary
  const entities = list(input.entities)
  if (entities) out.entities = entities
  const keywords = list(input.keywords)
  if (keywords) out.keywords = keywords
  const concepts = list(input.concepts)
  if (concepts) out.concepts = concepts
  return out
}

export async function save(input: SaveMemoryInput): Promise<SaveMemoryResult> {
  const now = Date.now()
  const tags = normalizeTags(input.tags)
  const weight = clampWeight(input.weight ?? defaultWeight(input.kind, input.category))
  // Explicit when the tool passed the origin mode; without it, the kind's default
  // — which keeps old memories behaving exactly as before.
  const scope = input.scope ?? defaultScopeOf(input.kind, input.category)

  let projectId: string | undefined
  let projectName: string | undefined
  let originProjectId: string | undefined
  let originProjectName: string | undefined
  if (input.kind === 'project') {
    if (!input.directory) throw new Error('Project memory requires the session working folder')
    projectId = projectIdOf(input.directory)
    projectName = path.basename(input.directory)
  } else if (input.directory) {
    // Global memory born inside a project: it still holds everywhere,
    // but it records the origin so the canvas anchors it to the right tree.
    originProjectId = projectIdOf(input.directory)
    originProjectName = path.basename(input.directory)
  }

  // Dedup (a secondary shield to the prompt): exact hash or nearly identical tags
  // within the same kind/project merge into the existing memory.
  const pool = (await alive()).filter(
    (m) => m.kind === input.kind && (input.kind !== 'project' || m.projectId === projectId),
  )
  const hash = hashText(input.text)
  const existing =
    input.dedup === false
      ? undefined
      : (pool.find((m) => hashText(m.text) === hash) ??
        (tags.length > 0
          ? pool.find((m) => m.tags.length > 0 && jaccard(m.tags, tags) >= JACCARD_THRESHOLD)
          : undefined))

  if (existing) {
    const merged: Memory = {
      ...existing,
      scope: mergeScope(existing, scope),
      // A proposal that repeats stays a proposal: the user is the one who decides.
      proposed: existing.proposed || input.proposed || undefined,
      tags: normalizeTags([...existing.tags, ...tags]),
      weight: Math.max(existing.weight, weight),
      lastHitAt: now,
      expiresAt: extendedExpiry(existing),
      originProjectId: existing.originProjectId ?? originProjectId,
      originProjectName: existing.originProjectName ?? originProjectName,
      ...enrichmentOf(input),
    }
    if (input.document) {
      await repo.writeDoc(merged.id, input.document)
      merged.hasDoc = true
    }
    await repo.put(merged)
    emit('updated', merged)
    if (input.relatedIds) {
      for (const relId of input.relatedIds) {
        await link(merged.id, relId, input.relatedTypes?.[relId])
      }
    }
    return { id: merged.id, merged: true, text: merged.text }
  }

  const memory: Memory = {
    id: newId(),
    kind: input.kind,
    scope,
    text: input.text.trim(),
    tags,
    weight,
    hits: 0,
    relatedIds: [],
    sessionId: input.sessionId,
    createdAt: now,
    expiresAt: ttlFor(input.kind, weight, input.category) != null
      ? now + ttlFor(input.kind, weight, input.category)!
      : null,
    projectId,
    projectName,
    directory: input.kind === 'project' ? input.directory : undefined,
    subproject: input.kind === 'project' ? input.subproject : undefined,
    originProjectId,
    originProjectName,
    proposed: input.proposed || undefined,
    // "project" and "general" ask for a category; the routine's proposal (seasonal)
    // carries its own, and it survives when the user promotes it. "core" never:
    // a personal fact is not classified.
    category: input.kind === 'core' ? undefined : input.category,
    area: input.kind === 'project' ? input.area : undefined,
    ...enrichmentOf(input),
  }
  if (input.document) {
    await repo.writeDoc(memory.id, input.document)
    memory.hasDoc = true
  }
  await repo.put(memory)
  emit('created', memory)
  if (input.relatedIds) {
    for (const relId of input.relatedIds) {
      await link(memory.id, relId, input.relatedTypes?.[relId])
    }
  }
  return { id: memory.id, merged: false, text: memory.text }
}

export interface SearchMemoryInput {
  query: string
  kinds: MemoryKind[]
  /** Filters project memories by project */
  projectId?: string
  category?: ProjectCategory
  /**
   * Mode of whoever is searching: discards what does not hold in it (visibleIn). The chat does
   * not see code knowledge; the code does not see conversation preferences.
   */
  mode?: 'chat' | 'code'
  limit?: number
}

/** How many graph neighbours come on top of the lexical result */
const GRAPH_EXPANSION_LIMIT = 4

/**
 * Attached documents of the memories in the set: what is inside the `.md`
 * also has to be findable, not just the memory text. It reads only those that
 * declare `hasDoc` and never takes the search down because of an unreadable document.
 */
async function docsFor(pool: Memory[]): Promise<Map<string, string>> {
  const withDoc = pool.filter((m) => m.hasDoc)
  if (withDoc.length === 0) return new Map()
  const out = new Map<string, string>()
  await Promise.all(
    withDoc.map(async (memory) => {
      try {
        const doc = await repo.readDoc(memory.id)
        if (doc?.trim()) out.set(memory.id, doc)
      } catch {
        /* an unreadable document does not invalidate the memory */
      }
    }),
  )
  return out
}

/**
 * Vectors from the semantic index, or empty when the model is not installed.
 * Searching never triggers a download: someone looking something up cannot wait for 130 MB.
 */
async function indexVectors(): Promise<Map<string, Float32Array>> {
  if (!modelInstalled()) return new Map()
  try {
    return await vectorsById()
  } catch {
    return new Map()
  }
}

/** Embedding of the query — undefined when the model is missing, and the search carries on lexical. */
async function queryVector(query: string): Promise<Float32Array | undefined> {
  try {
    const [vec] = await embedTexts([query])
    return vec
  } catch {
    return undefined
  }
}

export async function search(input: SearchMemoryInput): Promise<Memory[]> {
  const now = Date.now()
  const pool = (await alive()).filter((m) => {
    // A proposal is not a memory yet: it exists only for the review screen.
    if (m.proposed) return false
    if (!input.kinds.includes(m.kind)) return false
    if (m.kind === 'project' && m.projectId !== input.projectId) return false
    if (input.category && m.category !== input.category) return false
    if (input.mode && !visibleIn(m, input.mode)) return false
    return true
  })
  // A single lexical list — BM25 over the indexable text, with the attached `.md` —
  // fused with the query vector, at the bench calibration. Without a model, the
  // lexical one stands alone and the search keeps working.
  const docs = await docsFor(pool)
  const lexical = new Bm25Index(pool.map((memory) => lexicalDocOf(memory, docs.get(memory.id))))
  const vectors = await indexVectors()
  const queryVec = vectors.size > 0 ? await queryVector(input.query) : undefined
  const candidates = retrieveCandidates(
    { queryVec, lexicalQuery: input.query, vectors, lexical },
    PRODUCTION_RETRIEVAL,
  )

  const poolById = new Map(pool.map((m) => [m.id, m]))
  const limit = input.limit ?? 8
  const results: Memory[] = []
  for (const candidate of candidates) {
    const memory = poolById.get(candidate.id)
    if (!memory) continue
    results.push(memory)
    if (results.length >= limit) break
  }

  // Graph navigation: memories linked (relatedIds) to the best results
  // come into the return — e.g. the search finds the "Design System" node and brings along
  // the button/token memories linked to it, without depending on lexical tokens.
  const included = new Set(results.map((m) => m.id))
  const expanded: Memory[] = []
  for (const memory of results) {
    if (expanded.length >= GRAPH_EXPANSION_LIMIT) break
    for (const relatedId of memory.relatedIds) {
      if (included.has(relatedId)) continue
      const neighbor = poolById.get(relatedId)
      if (!neighbor) continue
      included.add(relatedId)
      expanded.push(neighbor)
      if (expanded.length >= GRAPH_EXPANSION_LIMIT) break
    }
  }

  // Only what matched the search counts as usage. The graph neighbours come
  // along for the ride, as context: counting them inflated hits on memories nobody
  // looked for — and hits decide promotion (context → decision) and which memory
  // survives when consolidation merges duplicates.
  const touched = results.map((memory) => hit(memory, now))
  await repo.putMany(touched)
  for (const next of touched) emit('updated', next)
  return [...touched, ...expanded]
}

function hit(memory: Memory, now: number): Memory {
  return { ...memory, hits: memory.hits + 1, lastHitAt: now, expiresAt: extendedExpiry(memory) }
}

/**
 * Reading a memory by the agent (memory_open) — counts as usage. With the project
 * map in the prompt, opening the node by id became the normal way to consult
 * memory; without counting, the most-read nodes would look "never used".
 */
export async function open(id: string): Promise<{ memory: Memory; document: string | null } | null> {
  const memory = await repo.get(id)
  if (!memory) return null
  const next = hit(memory, Date.now())
  await repo.put(next)
  emit('updated', next)
  const document = next.hasDoc ? await repo.readDoc(id) : null
  return { memory: next, document }
}

export async function getFull(id: string): Promise<{ memory: Memory; document: string | null } | null> {
  const memory = await repo.get(id)
  if (!memory) return null
  const document = memory.hasDoc ? await repo.readDoc(id) : null
  return { memory, document }
}

/** Replaces the attached markdown document (used by the re-init with merge). */
export async function setDocument(id: string, document: string): Promise<Memory | null> {
  const memory = await repo.get(id)
  if (!memory) return null
  await repo.writeDoc(id, document)
  const next: Memory = { ...memory, hasDoc: true }
  await repo.put(next)
  emit('updated', next)
  return next
}

export async function link(sourceId: string, targetId: string, type?: RelationType): Promise<boolean> {
  if (sourceId === targetId) return false
  const [source, target] = await Promise.all([repo.get(sourceId), repo.get(targetId)])
  if (!source || !target) return false
  const sourceRelationTypes = { ...(source.relationTypes ?? {}) }
  const targetRelationTypes = { ...(target.relationTypes ?? {}) }
  if (type === "parent") {
    // source (child) marks target as its parent
    sourceRelationTypes[targetId] = "parent"
    // target (parent) marks source as its child — needed for tree collapse
    targetRelationTypes[sourceId] = "parent"
  }
  const nextSource = { ...source, relatedIds: [...new Set([...source.relatedIds, targetId])], relationTypes: sourceRelationTypes }
  const nextTarget = { ...target, relatedIds: [...new Set([...target.relatedIds, sourceId])], relationTypes: targetRelationTypes }
  await repo.put(nextSource)
  await repo.put(nextTarget)
  emit('updated', nextSource)
  emit('updated', nextTarget)
  return true
}

/** Undoes the link between two memories, on both sides. */
export async function unlink(aId: string, bId: string): Promise<boolean> {
  const [a, b] = await Promise.all([repo.get(aId), repo.get(bId)])
  if (!a || !b) return false
  const drop = (m: Memory, other: string): Memory => {
    const relationTypes = { ...(m.relationTypes ?? {}) }
    delete relationTypes[other]
    return { ...m, relatedIds: m.relatedIds.filter((r) => r !== other), relationTypes }
  }
  const nextA = drop(a, bId)
  const nextB = drop(b, aId)
  await repo.put(nextA)
  await repo.put(nextB)
  emit('updated', nextA)
  emit('updated', nextB)
  return true
}

export async function linkAsParent(parentId: string, childId: string): Promise<boolean> {
  return link(parentId, childId, "parent")
}

/** Edit coming from the UI (text, tags, weight). */
export async function update(
  id: string,
  patch: Partial<Pick<Memory, 'text' | 'tags' | 'weight' | 'proposed'>>,
): Promise<Memory | null> {
  const memory = await repo.get(id)
  if (!memory) return null
  const next: Memory = {
    ...memory,
    ...(patch.text != null ? { text: patch.text.trim() } : undefined),
    ...(patch.tags != null ? { tags: normalizeTags(patch.tags) } : undefined),
    ...(patch.weight != null ? { weight: clampWeight(patch.weight) } : undefined),
    // Accepting the proposal (proposed: false) drops the flag for good.
    ...(patch.proposed != null ? { proposed: patch.proposed ? true : undefined } : undefined),
  }
  await repo.put(next)
  emit('updated', next)
  return next
}

export interface ReviseMemoryInput {
  /** Replaces the whole text (the agent rewrites it to include the new fact). */
  text?: string
  /** Replaces the tags. To add, use `addTags`. */
  tags?: string[]
  /** Adds tags while keeping the existing ones. */
  addTags?: string[]
  weight?: number
  /** Reclassification — this is how a misclassified general/learning becomes project. */
  kind?: MemoryKind
  /**
   * Moves the memory's scope (e.g. a conversation preference that proved
   * useful in the code becomes `both`). Absent: keeps the current one.
   */
  scope?: MemoryScope
  category?: ProjectCategory
  /** null removes the area (the node stops being labelled by it in the graph). */
  area?: ProjectArea | null
  /** Replaces the attached markdown. */
  document?: string
  /** Session folder — needed when promoting a memory to kind="project". */
  directory?: string
  /** Subfolder of the project the memory describes (only kind="project"). */
  subproject?: string
  /**
   * Enrichment for search. Rewriting the text of an old memory is the
   * chance to fill this in — without these fields it keeps being indexed
   * only by what can be derived from the text.
   */
  title?: string
  summary?: string
  entities?: string[]
  keywords?: string[]
  concepts?: string[]
}

/**
 * Revision of an existing memory by the agent. It is the alternative to creating a
 * duplicate: when a new fact merely refines something already saved, the
 * text is rewritten in place. It is also the way to fix classification — promoting a
 * "general" that was actually a project fact.
 */
export async function revise(id: string, input: ReviseMemoryInput): Promise<Memory | null> {
  const memory = await repo.get(id)
  if (!memory) return null

  const kind = input.kind ?? memory.kind
  let category = input.category ?? memory.category
  const weight = input.weight != null ? clampWeight(input.weight) : memory.weight

  // "learning" is exclusive to kind="general". When promoting a misclassified
  // learning to a project memory, the category has to come along — otherwise
  // the node would end up with a category the UI and the prompt cannot place.
  if (kind === 'project' && category === 'learning') {
    if (!input.category || input.category === 'learning') {
      throw new Error('Promoting to kind="project" requires a project category (learning is exclusive to general)')
    }
    category = input.category
  }
  // A personal fact (core) is not classified; the rest carries its own category.
  if (kind === 'core') category = undefined

  const next: Memory = {
    ...memory,
    kind,
    weight,
    ...(input.text != null ? { text: input.text.trim() } : undefined),
    ...(input.area != null ? { area: input.area } : undefined),
    ...(input.subproject != null && kind === 'project' ? { subproject: input.subproject } : undefined),
    ...(input.scope != null && kind === 'general' ? { scope: input.scope } : undefined),
    category,
    ...enrichmentOf(input),
  }
  if (input.area === null) delete next.area
  // Another kind with the same stored scope would create a meaningless combination
  // ("project" only in the chat). Except in seasonal → general, whose whole point is
  // not to let the repeated pattern escape the mode where it was born.
  if (input.scope == null && input.kind != null && input.kind !== memory.kind) {
    const inherited = memory.kind === 'seasonal' && kind === 'general'
    if (!inherited) delete next.scope
  }

  if (input.tags != null) next.tags = normalizeTags(input.tags)
  else if (input.addTags != null) next.tags = normalizeTags([...memory.tags, ...input.addTags])

  // It became a project memory: it needs a project identity so it does not vanish
  // from the canvas filter. The session folder takes precedence; the origin serves as fallback.
  if (kind === 'project' && !next.projectId) {
    const directory = input.directory ?? memory.directory
    if (!directory) {
      throw new Error('Promoting to kind="project" requires the session working folder')
    }
    next.projectId = projectIdOf(directory)
    next.projectName = path.basename(directory)
    next.directory = directory
  }
  if (kind !== 'project') {
    // It is no longer a project memory, but it was still born in one: the
    // origin preserves the canvas anchor instead of throwing it into the global group.
    next.originProjectId = memory.originProjectId ?? memory.projectId
    next.originProjectName = memory.originProjectName ?? memory.projectName
    next.projectId = undefined
    next.projectName = undefined
    next.directory = undefined
    next.subproject = undefined
    next.area = undefined
  }

  // Expiry is recalculated because kind/category/weight may have changed —
  // a context promoted to decision stops expiring, and the reverse path
  // has to get a fresh deadline instead of being born already due.
  const ttl = ttlFor(kind, weight, category)
  next.expiresAt = ttl == null ? null : (memory.expiresAt ?? Date.now() + ttl)

  if (input.document != null) {
    await repo.writeDoc(id, input.document)
    next.hasDoc = true
  }

  await repo.put(next)
  emit('updated', next)
  return next
}

export interface TreeNodeSummary {
  id: string
  text: string
  area?: ProjectArea
  category?: ProjectCategory
  subproject?: string
  depth: number
  childIds: string[]
}

/**
 * Skeleton of a project's tree: each node with id, label and children. It is what the
 * agent reads before saving to choose WHOM to connect to — without it, it has no
 * way to know a "Design System" node exists and ends up creating a loose node.
 */
export async function tree(projectId: string): Promise<TreeNodeSummary[]> {
  const members = (await alive()).filter((m) => m.kind === 'project' && m.projectId === projectId)
  if (members.length === 0) return []
  const byId = new Map(members.map((m) => [m.id, m]))

  const root = rootOf(members)!

  const depth = new Map<string, number>([[root.id, 0]])
  const childrenOf = new Map<string, string[]>()
  const queue = [root.id]
  while (queue.length) {
    const id = queue.shift()!
    for (const rel of byId.get(id)?.relatedIds ?? []) {
      if (!byId.has(rel) || depth.has(rel)) continue
      depth.set(rel, depth.get(id)! + 1)
      childrenOf.set(id, [...(childrenOf.get(id) ?? []), rel])
      queue.push(rel)
    }
  }

  return members
    .map((m) => ({
      id: m.id,
      text: m.text,
      area: m.area,
      category: m.category,
      subproject: m.subproject,
      depth: depth.get(m.id) ?? 99,
      childIds: childrenOf.get(m.id) ?? [],
    }))
    .sort((a, b) => a.depth - b.depth || (a.area ?? '').localeCompare(b.area ?? ''))
}

/**
 * Promotes in place: seasonal → general; project/context → decision.
 * `promotedFrom` records the origin (previous kind/category) for the UI.
 *
 * `general` and not `core`: core is only injected into the chat prompt (see
 * loadPromptContext), and a pattern that repeats matters mostly in the code —
 * promoting it to core would make it disappear exactly there.
 *
 * The scope is STORED on promotion (the seasonal/context one, derived before the
 * kind switch): without that, a chat seasonal would become a `general` with no field and,
 * by the kind default, would also start to hold in the code — exactly the
 * leak the field exists to prevent.
 */
export async function promote(id: string): Promise<Memory | null> {
  const memory = await repo.get(id)
  if (!memory) return null
  const inheritedScope = scopeOf(memory)
  let next: Memory | null = null
  if (memory.kind === 'seasonal') {
    next = { ...memory, kind: 'general', scope: inheritedScope, expiresAt: null, promotedFrom: 'seasonal' }
  } else if (memory.kind === 'project' && memory.category === 'context') {
    next = { ...memory, category: 'decision', expiresAt: null, promotedFrom: 'project/context' }
  }
  if (!next) return null
  await repo.put(next)
  emit('promoted', next)
  return next
}

export async function remove(id: string): Promise<void> {
  const memory = await repo.get(id)
  if (!memory) return
  const touched = await repo.remove(id)
  emit('removed', memory)
  for (const m of touched) emit('updated', m)
}

export async function list(): Promise<Memory[]> {
  return repo.getIndex()
}

export interface ProjectScope {
  projectId: string
  /** Root folder of the project — where its memories are written. */
  directory: string
  projectName: string
  /** Relative path of the requested folder inside the root ("front", "front/src"). */
  subproject?: string
  /** A memory tree already covers the folder (in it or in a folder above). */
  covered: boolean
}

/**
 * Memory project of a working folder. Everything that reads or writes project
 * memory goes through here, and not through projectIdOf directly: it is what makes a chat
 * opened in "app/front" see (and feed) the tree that /init created in
 * "app/". With no tree above, the project is the folder itself, as it always was.
 */
export async function resolveProjectScope(folder: string): Promise<ProjectScope> {
  // A worktree is the same project at another path: the memory is the main one's.
  const directory = await folderInMainRepository(folder)
  const roots = new Map<string, ProjectRoot>()
  for (const m of await alive()) {
    if (m.kind !== 'project' || m.area !== 'overview' || m.subproject || !m.directory || !m.projectId) continue
    if (!roots.has(m.projectId)) roots.set(m.projectId, { projectId: m.projectId, directory: m.directory })
  }
  const picked = pickProjectRoot([...roots.values()], directory)
  if (!picked) {
    return { projectId: projectIdOf(directory), directory, projectName: path.basename(directory), covered: false }
  }
  return {
    projectId: picked.root.projectId,
    directory: picked.root.directory,
    projectName: path.basename(picked.root.directory),
    subproject: picked.subproject,
    covered: true,
  }
}

export interface PromptContext {
  core: Memory[]
  seasonal: Memory[]
  /**
   * Seasonals that have repeated enough to become a pattern. The agent asks
   * in the conversation before promoting — it is the user's "yes" that makes the rule.
   */
  promotable: Memory[]
  general: Memory[]
  /** kind="general" + category="learning" — lessons reusable across projects */
  learning: Memory[]
  project: Memory[]
  projectName?: string
  /** Slice of the project tree for the prompt (code mode). */
  map?: ProjectMap
  /** Subfolder of the project the chat is in, when it is not the root. */
  subproject?: string
}

const CATEGORY_PRIORITY: Record<ProjectCategory, number> = {
  decision: 0,
  convention: 1,
  preference: 2,
  standard: 2,
  database: 3,
  structure: 3,
  context: 4,
  learning: 4,
}

/**
 * How many uses make a seasonal look like a pattern. It sits BELOW the threshold of
 * automatic promotion (5 — see shouldPromote): the idea is for the agent to ask
 * BEFORE the system decides on its own, because the rule should only be born with the approval
 * of whoever will live with it. Automatic promotion remains as a safety
 * net for when nobody asked (brain off, session closed).
 */
const PROMOTION_ASK_HITS = 3

function repeatingSeasonals(pool: Memory[], now: number): Memory[] {
  return pool
    .filter((m) => m.kind === 'seasonal' && !isExpired(m, now) && m.hits >= PROMOTION_ASK_HITS)
    .sort((a, b) => b.hits - a.hits)
    .slice(0, 3)
}

/**
 * Budget of the system prompt block, in characters.
 *
 * The limit is on SIZE, not on a count of memories: counting items does not
 * protect against one long memory, and that was how a text of thousands of
 * characters went into the prompt whole — on every message, forever.
 */
const CONTEXT_BUDGET_CHARS = 3600

/** Per-line ceiling: one long memory cannot swallow the block. */
const CONTEXT_LINE_MAX_CHARS = 220

/**
 * Trims the block to fit the budget, in the prompt's priority order:
 * the permanent first, the occasional after. When the budget runs out, what
 * comes next stays out — and that is the right behaviour, not a tie.
 */
function trimContext(ctx: PromptContext): PromptContext {
  let used = 0
  const take = (list: Memory[]): Memory[] => {
    const out: Memory[] = []
    for (const memory of list) {
      const text =
        memory.text.length > CONTEXT_LINE_MAX_CHARS
          ? `${memory.text.slice(0, CONTEXT_LINE_MAX_CHARS - 1).trimEnd()}…`
          : memory.text
      const cost = text.length + 8 // line marker and separator
      if (used + cost > CONTEXT_BUDGET_CHARS) break
      used += cost
      out.push(text === memory.text ? memory : { ...memory, text })
    }
    return out
  }
  return {
    ...ctx,
    core: take(ctx.core),
    project: take(ctx.project),
    general: take(ctx.general),
    learning: take(ctx.learning),
    seasonal: take(ctx.seasonal),
    promotable: take(ctx.promotable),
  }
}

/**
 * Memories injected silently into the system prompt, already trimmed to fit
 * the `CONTEXT_BUDGET_CHARS` budget (see trimContext).
 */
export async function loadPromptContext(
  mode: 'chat' | 'code',
  directory?: string,
): Promise<PromptContext> {
  // A proposal does not enter the prompt: it is not a memory yet.
  const pool = (await alive()).filter((m) => !m.proposed)
  const byWeight = (a: Memory, b: Memory) => b.weight - a.weight
  const generalAll = pool.filter((m) => m.kind === 'general')
  const learningPool = generalAll.filter((m) => m.category === 'learning' && visibleIn(m, 'code'))
  // A preference that only holds in the chat is not injected into the code prompt — and
  // vice versa. It is the same rule as the search, so the two paths do not tell
  // different stories about the same pool.
  const general = generalAll
    .filter((m) => m.category !== 'learning' && visibleIn(m, mode))
    .sort(byWeight)
  const promotable = repeatingSeasonals(pool.filter((m) => visibleIn(m, mode)), Date.now())
  // The candidate does not repeat in the context block: the same line twice
  // (once as "use as context", once as "ask") only confuses.
  const promotableIds = new Set(promotable.map((m) => m.id))

  if (mode === 'chat') {
    return trimContext({
      core: pool.filter((m) => m.kind === 'core').sort(byWeight).slice(0, 15),
      seasonal: pool
        .filter((m) => m.kind === 'seasonal' && !promotableIds.has(m.id))
        .sort((a, b) => b.createdAt - a.createdAt)
        .slice(0, 8),
      promotable,
      general: general.slice(0, 10),
      // Lessons are code context ("Prisma on Alpine needs openssl")
      // and do not help at all in a conversation — injecting them here only burned tokens
      // and mixed the two contexts.
      learning: [],
      project: [],
    })
  }

  const scope = directory ? await resolveProjectScope(directory) : undefined
  const projectId = scope?.projectId
  const members = projectId ? pool.filter((m) => m.kind === 'project' && m.projectId === projectId) : []
  // The central graph node (overview area) always comes first — it is the map
  // that guides the agent to look up the satellite areas as the task requires
  const areaRank = (m: Memory) => (m.area === 'overview' ? -1 : 0)
  const project = projectId
    ? [...members]
        .sort(
          (a, b) =>
            areaRank(a) - areaRank(b) ||
            CATEGORY_PRIORITY[a.category ?? 'context'] - CATEGORY_PRIORITY[b.category ?? 'context'] ||
            b.weight - a.weight,
        )
        .slice(0, 15)
    : []

  // Lessons from OTHER projects with a stack/theme in common (tags crossing
  // the tags already collected in this project) come up first; the rest complete
  // by weight — so an Expo "gotcha" learned in project A already enters the
  // context when opening a project B that also uses Expo.
  const projectTags = new Set(project.flatMap((m) => m.tags))
  const learning = learningPool
    .map((m) => ({ m, overlap: m.tags.some((t) => projectTags.has(t)) ? 1 : 0 }))
    .sort((a, b) => b.overlap - a.overlap || b.m.weight - a.m.weight)
    .slice(0, 5)
    .map(({ m }) => m)

  return trimContext({
    core: [],
    seasonal: [],
    promotable,
    general: general.slice(0, 8),
    learning,
    project,
    projectName: scope?.covered ? scope.projectName : project[0]?.projectName,
    map: buildProjectMap(members, scope?.subproject) ?? undefined,
    subproject: scope?.subproject,
  })
}

/** Run by the scheduler: expires (cascading to the doc) and promotes automatically. */
/** A proposal nobody reviewed does not become memory: after this long, it goes away on its own. */
const PROPOSAL_TTL = 14 * 24 * 60 * 60 * 1000

export async function cleanup(): Promise<void> {
  const now = Date.now()
  const index = await repo.getIndex()
  for (const memory of index) {
    // The proposal waits for review: it neither expires nor promotes, it only ages.
    if (memory.proposed) {
      if (now - memory.createdAt > PROPOSAL_TTL) await remove(memory.id)
      continue
    }
    if (isExpired(memory, now)) {
      await remove(memory.id)
      continue
    }
    const promotion = shouldPromote(memory, now)
    if (promotion) {
      const next: Memory = {
        ...memory,
        kind: promotion.kind,
        // Stored before the kind switch: the promotion inherits the origin scope
        // instead of falling back to the new kind's default.
        scope: scopeOf(memory),
        category: promotion.category ?? memory.category,
        expiresAt: null,
        promotedFrom: memory.kind === 'seasonal' ? 'seasonal' : 'project/context',
      }
      await repo.put(next)
      emit('promoted', next)
    }
  }
}

