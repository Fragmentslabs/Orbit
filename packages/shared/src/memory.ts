/**
 * Memory that belongs to the CODE context and must never show up in the chat.
 *
 * `kind="project"` is obvious. The subtle case is `category="learning"`: it is
 * saved with `kind="general"` so it can cross from one project to another,
 * but it is still technical knowledge produced in code mode — only code
 * mode can create it (the chat's memory_save does not even expose `category`).
 * Without this check, the learnings leaked into the chat canvas, into the chat
 * search and into the chat system prompt.
 */
export function isCodeContext(memory: Pick<Memory, "kind" | "category">): boolean {
  return memory.kind === "project" || memory.category === "learning"
}

export function defaultScopeOf(kind: MemoryKind, category?: ProjectCategory): MemoryScope {
  if (kind === "project" || category === "learning") return "code"
  if (kind === "general") return "both"
  return "chat"
}

/**
 * Effective scope: the saved field decides; without it, the default of the kind applies. That way
 * a memory promoted from `seasonal` to `general` stays in the chat if the scope was saved in
 * the memory before the promotion (see service.promote).
 */
export function scopeOf(memory: Pick<Memory, "kind" | "category" | "scope">): MemoryScope {
  return memory.scope ?? defaultScopeOf(memory.kind, memory.category)
}

/** Does the memory appear in this mode? It is the only access rule between chat and code. */
export function visibleIn(
  memory: Pick<Memory, "kind" | "category" | "scope">,
  mode: "chat" | "code",
): boolean {
  const scope = scopeOf(memory)
  return scope === "both" || scope === mode
}

export type RelationType = "parent" | "related"

export interface Memory {
  id: string
  kind: MemoryKind
  /**
   * Where the memory is worth. Absent = the default of the kind (it is the case of every memory
   * saved before this field). `both` is only saved when the agent decides, at
   * save time, that the fact crosses both modes.
   */
  scope?: MemoryScope
  /** Short summary — it is what enters the system prompt and the search */
  text: string
  tags: string[]
  /** Importance 0..1 (the agent decides, never the user) */
  weight: number
  hits: number
  lastHitAt?: number
  /** Bidirectional backlinks (Obsidian style) */
  relatedIds: string[]
  /**
   * Type of the relation by destination id. When absent, it assumes "related".
   * "parent" = explicit hierarchy (child node of this node).
   * A memory can be the parent of several children and related to several other nodes.
   */
  relationTypes?: Record<string, RelationType>
  /** There is a markdown document attached at memory/docs/<id>.md */
  hasDoc?: boolean
  sessionId?: string
  messageId?: string
  createdAt: number
  /** null/undefined = never expires */
  expiresAt?: number | null
  /** id of the memory that originated this one via promotion */
  promotedFrom?: string
  /**
   * Proposal from the memory routine: it is born to be reviewed and does not
   * enter the prompt, the search or the retrieval while unaccepted.
   */
  proposed?: boolean
  // Only when kind === "project":
  projectId?: string
  projectName?: string
  directory?: string
  /**
   * Project in which the memory was created, for kinds that are NOT "project"
   * (general/core/seasonal). It does not isolate the memory — it keeps being worth in
   * all projects —, but it anchors the node near the tree of origin on the canvas and
   * lets the filter hide learnings born in other projects.
   */
  originProjectId?: string
  originProjectName?: string
  /** Subproject inside the project (e.g. "front", "back") — undefined = root scope */
  subproject?: string
  /**
   * Required when kind === "project". It is also worth for kind === "general":
   * "learning" describes a technical lesson; preference, convention, decision and
   * standard describe how the person works.
   */
  category?: ProjectCategory
  /** Knowledge area (generated by /init) — base of the memory graph */
  area?: ProjectArea
  /**
   * Enrichment fields for the search (all optional; `text` keeps
   * being the source of truth). Whoever saves the memory — the LLM, via memory_save —
   * can fill them in at no extra cost; when absent, the index derives them from the
   * text (see memory-retrieval.ts). They never contain facts the text does not have.
   */
  title?: string
  summary?: string
  /** People, projects, products, places and identifiers mentioned */
  entities?: string[]
  keywords?: string[]
  /** Paraphrases and intentions that should lead to this memory (any language) */
  concepts?: string[]
}

export interface MemoryEvent {
  action: "created" | "updated" | "removed" | "promoted"
  memory: Memory
}

