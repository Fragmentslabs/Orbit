const STOPWORDS = new Set([
  // pt (without accents — the texts are normalized beforehand)
  "de", "da", "do", "das", "dos", "a", "o", "as", "os", "um", "uma", "uns", "umas",
  "e", "ou", "que", "em", "no", "na", "nos", "nas", "para", "por", "com", "sem",
  "se", "ao", "aos", "e", "sao", "foi", "ser", "tem", "mais", "menos", "muito",
  "como", "mas", "meu", "minha", "seu", "sua", "ele", "ela", "eu", "voce",
  "isso", "isto", "esse", "essa", "este", "esta", "ja", "nao", "sim", "quando",
  "onde", "qual", "quais", "tambem", "sobre", "entre", "ate", "depois", "antes",
  // en
  "the", "an", "and", "or", "of", "to", "in", "on", "at", "for", "with",
  "without", "is", "are", "was", "were", "be", "been", "has", "have", "had",
  "do", "does", "did", "not", "no", "yes", "it", "this", "that", "these",
  "those", "you", "he", "she", "we", "they", "my", "your", "his", "her",
  "their", "our", "as", "by", "from", "but", "if", "so", "than", "then",
  "when", "where", "which", "what", "who", "how", "about", "into", "over",
  "after", "before", "between", "more", "most", "less", "very", "can", "will",
  "just", "also",
])

/** lowercase, without accents, spaces collapsed — base of the dedup hash and of the search */
export function normalizeText(text: string): string {
  return text
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/\s+/g, " ")
    .trim()
}

export function tokenize(text: string): string[] {
  return normalizeText(text)
    .split(/[^a-z0-9]+/)
    .filter((t) => t.length >= 2 && !STOPWORDS.has(t))
}

/** Jaccard similarity between two sets of tags (normalized) */
export function jaccard(a: string[], b: string[]): number {
  const setA = new Set(a.map(normalizeText))
  const setB = new Set(b.map(normalizeText))
  if (setA.size === 0 && setB.size === 0) return 0
  let intersection = 0
  for (const t of setA) if (setB.has(t)) intersection++
  const union = setA.size + setB.size - intersection
  return union === 0 ? 0 : intersection / union
}

/**
 * Weight of a token found only in the attached document. Calibrated on the real collection
 * (307 memories, 58 with a document) against 46 queries that only the `.md` answers and
 * 306 text queries, which serve as a regression control:
 *
 *   weight   R@1 (doc)   R@5 (doc)   R@1 (text)
 *   0.6      56.5%       89.1%        96.7%
 *   0.8      65.2%       97.8%        96.4%
 *   0.9      80.4%       97.8%        96.4%
 *   1.0      87.0%       97.8%        95.8%   ← the text starts to give way
 *
 * 0.9 is the knee: R@5 saturates at 0.8 and from there on what is bought is order
 * (R@1), not reach. Staying at 1.0 yields another 6.6 pp on the document, but it costs
 * 1.3 pp on the text queries — and those are the format closest to a real
 * question, while the document ones were built to favor it.
 */
export const DOC_TOKEN_WEIGHT = 0.9

/**
 * Lexical score: exact tag ×3, token in the text ×1, token in the attached document ×0.6,
 * + 0.5×weight + hit boost. The `else if` guarantees that a token present in
 * both counts once only (the text wins, which is the strongest signal).
 * Returns 0 when no token of the query matches (irrelevant memory).
 */
export function scoreMemory(
  memory: Pick<Memory, "text" | "tags" | "weight" | "hits">,
  queryTokens: string[],
  doc?: string | null,
  docWeight = DOC_TOKEN_WEIGHT,
): number {
  if (queryTokens.length === 0) return 0
  const text = normalizeText(memory.text)
  const body = doc ? normalizeText(doc) : ""
  const tags = new Set(memory.tags.map(normalizeText))
  let matches = 0
  for (const token of queryTokens) {
    if (tags.has(token)) matches += 3
    else if (text.includes(token)) matches += 1
    else if (body.includes(token)) matches += docWeight
  }
  if (matches === 0) return 0
  return matches + 0.5 * memory.weight + Math.min(memory.hits / 10, 0.3)
}

/**
 * Orders a set of memories by relevance to the query and cuts at the limit.
 * `docs` carries the attached document by id — without it the behavior is the one of
 * before, byte by byte.
 */
export interface SearchOptions {
  /** Attached document by memory id */
  docs?: Map<string, string>
  /** Weight of a token found only in the document (default: DOC_TOKEN_WEIGHT) */
  docWeight?: number
}

export function searchMemories<T extends Memory>(
  pool: T[],
  query: string,
  limit = 8,
  options: SearchOptions = {},
): T[] {
  const tokens = tokenize(query)
  const docWeight = options.docWeight ?? DOC_TOKEN_WEIGHT
  return pool
    .map((memory) => ({ memory, score: scoreMemory(memory, tokens, options.docs?.get(memory.id), docWeight) }))
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((entry) => entry.memory)
}
