export const MEDIA_SCHEME = "orbit-media"
export const ARTIFACT_SCHEME = "orbit-artifact"
/** Audio (attached and generated): its own scheme, with the `stream` privilege that <audio> requires. */
export const AUDIO_SCHEME = "orbit-audio"
/**
 * Videos the agent rendered (video editing): served straight from the project
 * file, with Range — a video is not copied to the app folder.
 */
export const VIDEO_SCHEME = "orbit-video"
/**
 * Motion compositions (project folder: HTML entry + dependencies that the
 * preview serves, with `corsEnabled` — fonts and `<script type="module">` in an
 * opaque origin require CORS). Unlike videos, here a FOLDER is served.
 */
export const MOTION_SCHEME = "orbit-motion"
/**
 * Design canvas (app folder: canvas.json + one .html per artboard, served
 * statically — no injected runtime, since there is no timeline and no seek). Same
 * `corsEnabled` as motion: @font-face font and fetch inside the artboard require CORS.
 */
export const DESIGN_SCHEME = "orbit-design"
/**
 * Slides decks (folder: `index.html` with one `<section class="slide">` per
 * slide, served with the navigation runtime injected). Same flags as design:
 * the deck is self-contained HTML, but the runtime talks to the tab over postMessage and
 * the library fonts require CORS.
 */
export const SLIDES_SCHEME = "orbit-slides"
/**
 * Fonts downloaded by Orbit (library in `orbit-data/fonts`). Served
 * per file with a hash in the name, `corsEnabled` and `Access-Control-Allow-Origin: *`:
 * the artboard, the motion composition and the app window itself (another origin)
 * declare the same font through `@font-face`.
 */
export const FONT_SCHEME = "orbit-font"

/**
 * MIME of the internal drag & drop: the tile of the Media tab drags the item AS AN ATTACHMENT
 * to the composer. The payload carries only the IDENTITY of the item (id, name, type and a
 * preview URL) — never the bytes: the attachment is a REFERENCE to the file that already
 * exists in the gallery, so nothing is copied nor pasted as text into the input. Without
 * this the native drag of the <img> carried only the URL text and the drop pasted the
 * path into the field.
 */
export const MEDIA_DND_MIME = "application/x-orbit-media"

/** Normalized `kind` — old records do not have the field. */
export function mediaKind(entry: Pick<MediaEntry, "kind">): MediaKind {
  return entry.kind ?? "image"
}

/**
 * MIME of a gallery entry. The record does not store MIME (the id is the source of
 * truth) — it comes from the extension of the id and, if it is not recognized, from `kind`.
 * It is what the composer uses to decide whether to show the thumbnail in the chip.
 */
const MIME_BY_EXT: Record<string, string> = {
  png: "image/png",
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  webp: "image/webp",
  gif: "image/gif",
  svg: "image/svg+xml",
  mp4: "video/mp4",
  m4v: "video/x-m4v",
  mov: "video/quicktime",
  webm: "video/webm",
  mkv: "video/x-matroska",
  avi: "video/x-msvideo",
  mp3: "audio/mpeg",
  wav: "audio/wav",
  m4a: "audio/mp4",
  aac: "audio/aac",
  ogg: "audio/ogg",
  oga: "audio/ogg",
  opus: "audio/opus",
  flac: "audio/flac",
  weba: "audio/webm",
  html: "text/html",
  htm: "text/html",
  md: "text/markdown",
  pdf: "application/pdf",
  docx: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
}

const KIND_FALLBACK_MIME: Record<MediaKind, string> = {
  image: "image/png",
  video: "video/mp4",
  audio: "audio/mpeg",
  artifact: "text/html",
  document: "text/markdown",
  motion: "text/html",
  design: "text/html",
  slides: "text/html",
}

export function mediaMime(entry: Pick<MediaEntry, "id" | "kind">): string {
  const ext = entry.id.split(".").pop()?.toLowerCase() ?? ""
  return MIME_BY_EXT[ext] ?? KIND_FALLBACK_MIME[mediaKind(entry)]
}

/**
 * Id of an attached video (`vdo_…`): the file name in the app's video
 * attachments folder. It lives here, and not in the main, because media.ts (which deletes the file) and
 * attachment-ref.ts (which stores it) need the SAME format and one imports the other.
 */
export const SAFE_VIDEO_MEDIA_ID = /^vdo_[a-z0-9]+\.(mp4|m4v|mov|webm|mkv|avi)$/

/**
 * URL that OPENS the asset: the image itself, the HTML of the artifact, or — in the
 * document case — the preview HTML, because Electron has no PDF viewer
 * and .docx is not renderable in the browser. PDF and DOCX are delivery
 * (open outside, export), not embedded viewing.
 */
export function assetUrl(entry: Pick<MediaEntry, "id" | "kind" | "thumb" | "thumbDark" | "revision" | "videoUrl">): string {
  const kind = mediaKind(entry)
  if (kind === "artifact") return `${ARTIFACT_SCHEME}://${entry.id}`
  if (kind === "document") return `${ARTIFACT_SCHEME}://${documentPreviewId(entry.id)}`
  if (kind === "audio") return `${AUDIO_SCHEME}://${entry.id}`
  // The piece has no file of its own to open: the only byte kept in the gallery
  // is the COVER (the composition is a project folder, served by
  // orbit-motion:// and reopened by the tab). Without this line the cover id would be
  // The piece has no file of its own to open: the only byte kept in the gallery
  if (kind === "motion") return thumbUrl(entry) ?? `${MEDIA_SCHEME}://${entry.id}`
  // is the COVER (the composition is a project folder, served by
  // orbit-motion:// and reopened by the tab). Without this line the cover id would be
  if (kind === "design") return thumbUrl(entry) ?? `${MEDIA_SCHEME}://${entry.id}`
  // asked to the wrong scheme and would come back empty.
  // here only the cover exists.
  if (kind === "slides") return thumbUrl(entry) ?? `${MEDIA_SCHEME}://${entry.id}`
  // Same case as motion: the canvas lives in the app folder, not in the gallery — the
  if (kind === "video") return entry.videoUrl ?? thumbUrl(entry) ?? `${MEDIA_SCHEME}://${entry.id}`
  return `${MEDIA_SCHEME}://${entry.id}`
}

// only byte kept here is the cover.
export function documentPreviewId(id: string): string {
  return id.replace(/\.md$/, '.html')
}

/**
 * THUMBNAIL URL for the grid — null when the artifact has no capture and the
 * tile has to fall back to the icon.
 *
 * The artifact thumbnail is rewritten with the SAME name on every
 * update_artifact, so the revision enters the query: without it the grid would keep
 * showing the capture of the previous version.
 */
export function thumbUrl(
  entry: Pick<MediaEntry, "id" | "kind" | "thumb" | "thumbDark" | "revision">,
  dark = false,
): string | null {
  if (mediaKind(entry) === "image") return `${MEDIA_SCHEME}://${entry.id}`
  // And the deck: the file is the index.html of the folder, served by orbit-slides://;
  if (mediaKind(entry) === "audio") return null
  // here only the cover exists.
  const thumb = (dark && entry.thumbDark) || entry.thumb
  return thumb ? `${ARTIFACT_SCHEME}://${thumb}?rev=${entry.revision ?? 1}` : null
}

/**
 * Where the document opens in the side panel.
 *
 * Requested as a file (or coming from outside), it opens in the document VIEWER —
 * the same panel as the attached PDF, with outline, find, zoom and print, which
 * is what one wants from a finished file. A live Markdown document opens in the
 * canvas, where it can be read and edited.
 */
export function documentOpensAsFile(
  doc: Pick<MediaEntry, "delivery" | "derived">,
): boolean {
  return doc.derived === true || (doc.delivery?.length ?? 0) > 0
}

// The video plays through the player URL; without it (record without player) it falls back to the cover.
export function documentFileName(title: string, format: DocumentDownload): string {
  const base = title.replace(/[\\/:*?"<>|]/g, "-").trim().slice(0, 60) || "document"
  return `${base}.${format}`
}

/**
 * A FILE of a composition's folder — what the piece card in the chat lists.
 *
 * The piece has a folder with the HTML, the media, the fonts and the material the agent
 * brought into it. In the chat, each of those files was born as a loose player
 * in the message; the card gathers all the files of the SAME piece and says, for each one, whether it
 * is being used by the composition or was left out.
 *
 * Nothing is deleted: "discarded" is a FILE THE COMPOSITION DOES NOT REFERENCE (the
 * old narration, the rejected image). It stays in the folder, in the gallery and in the
 * card — with the tag.
 */
export interface MotionBundleFile {
  /** Relative path inside the piece folder, always with `/`. */
  name: string
  /** Size in bytes (0 when the file disappeared from disk after being listed). */
  size: number
  kind: "audio" | "image" | "video" | "font" | "file"
  /** The composition references this file (index.html, audio.json or one of its CSS/JS). */
  used: boolean
  /** When it entered the piece (ms). Without a record, the file mtime. */
  addedAt: number
}

/** Everything the chat needs to know about a piece to draw its card. */
export interface MotionBundle {
  /** Id of the composition in the main registry (`mv_…`). */
  motionId: string
  /** Name of the piece (the name of its folder). */
  name: string
  /** Folder of the piece, for "Open folder". */
  folder: string
  /** The files, from the most recently registered to the oldest. */
  files: MotionBundleFile[]
  totalBytes: number
  /** How many are not referenced by the composition. */
  discarded: number
  /**
   * Identifiers that link a media of the CHAT to this piece: the attachment
   * references each file came from (`aud_…`, `img_…`, `vdo_…`) and the source
   * paths (code mode). Already normalized by `motionBundleKey` — the
   * comparison is made with that same function on both sides.
   */
  keys: string[]
}

/**
 * Comparable key of a media: the ID the URL carries, without scheme and without
 * query, lowercased.
 *
 * `orbit-audio://aud_x.wav` → `aud_x.wav`; `orbit-media://img_y.png` →
 * `img_y.png`; `orbit-video://vid_z` → `vid_z`. An absolute path goes
 * whole (normalized slashes), because that is how a video rendered in the
 * project is identified. It is this function that decides whether a loose player in the chat
 * belongs to the piece.
 */
export function motionBundleKey(value: string): string | null {
  const clean = value.trim()
  if (!clean) return null
  const scheme = /^(?:orbit-media|orbit-audio|orbit-video|orbit-motion):\/\/(.+)$/i.exec(clean)
  const raw = (scheme ? scheme[1] : clean).split(/[?#]/)[0].replace(/\/+$/, "")
  if (!raw) return null
  return raw.replace(/\\/g, "/").toLowerCase()
}

