/**
 * Registry of assets produced by the agent: every image (show_image,
 * screenshots, browser scripts), every image pasted by the user and every
 * HTML artifact (create_artifact) gets a record in
 * orbit-data/media/index.json. The gallery of the right panel reads from here.
 *
 * The index is single, but the BYTES live where it makes sense: images in
 * orbit-data/media, artifacts in orbit-data/artifacts. Nothing is duplicated — the
 * record is a pointer (`path` is absolute) and `kind` says how to open.
 */

export type MediaSource = "chat" | "user" | "screenshot" | "script" | "batch"

/**
 * Where an image fetched from the web came from and under which license — what the license
 * usually requires to appear alongside when it is used (CC BY, CC BY-SA). It stays in the
 * media item so the credit follows the image all the way to the piece.
 */
export interface MediaCredit {
  title?: string
  creator?: string
  /** "CC BY-SA 4.0", "CC0 1.0", "Public domain"… */
  license: string
  licenseUrl?: string
  /** Source page of the image (where the author and the license are confirmed). */
  sourceUrl: string
  provider: "commons" | "openverse"
  /** The ready credit line, to put in a caption or on the final screen. */
  attribution: string
}

/**
 * Image (the historical case), renderable HTML artifact, document
 * (report/proposal authored by the agent, delivered as PDF and/or DOCX), audio
 * (attached by the user or generated by the agent) or motion (a piece: the
 * composition is a FOLDER of the project and nothing of it is copied here — the record
 * keeps the cover and the `motionId`, and opening is reopening the Motion tab) or video (a
 * video attached by the user, or produced in the chat: the file lives in the app, the
 * record keeps the cover and the playback URL). Design and slides are siblings of
 * motion: the canvas and the deck are FOLDERS (of the app or of the project), nothing of them is
 * copied here beyond the cover, and opening is reopening the tab.
 * Absent in records written before this existed = "image".
 */
export type MediaKind = "image" | "artifact" | "document" | "audio" | "motion" | "video" | "design" | "slides"

/** Delivery formats of a document. The source is always Markdown; these are
 *  the files rendered from it. */
export type DocumentFormat = "pdf" | "docx"

/**
 * What can be DOWNLOADED from a document. The `.md` is the source itself, copied
 * as is; PDF and DOCX are rendered on the spot when they do not exist on
 * disk yet.
 *
 * The document is BORN only in Markdown: rendering at creation cost one Chromium
 * window per document, and most never become a file — the user reads it in the
 * chat and moves on. That is why this list is FIXED, and not the `formats` of the record, which
 * says only what is already cached.
 */
export type DocumentDownload = DocumentFormat | "md"

export const DOCUMENT_DOWNLOADS: DocumentDownload[] = ["md", "pdf", "docx"]

export interface MediaEntry {
  /** File name (it is also the URL: orbit-media://<id> or orbit-artifact://<id>) */
  id: string
  /** URL ready to display. On the desktop it comes from `assetUrl`; on the companion the
   *  server fills it with http://host/api/media/<id>?t=<signed token>. */
  url?: string
  /** Absolute path on disk — the source of truth to read/delete the file,
   *  since images and artifacts live in different directories. */
  path: string
  size: number
  createdAt: number
  source: MediaSource
  kind?: MediaKind
  /** Chat that originated the asset (when it came from a tool) */
  sessionId?: string
  /**
   * Other sessions in which this asset should also show up under "In this chat" —
   * today, only forks. `forkSession` clones the messages with new part ids,
   * but points to the SAME documentId/mediaUrl (nothing is duplicated); without this,
   * the card stays visible in the fork conversation, but vanishes from the "In this
   * chat" filter because `sessionId` here is fixed to the original session.
   *
   * `directory`/`folderId` stay derived from `sessionId` (the session of
   * origin) — a fork inherits the same project at creation, so there is no reason
   * for those two scopes to need a list too.
   */
  linkedSessionIds?: string[]
  /** Assistant message where the asset appears */
  messageId?: string
  /** Task of run_browser_script/capture_batch that generated the image */
  taskId?: string
  /**
   * Image from which this one was derived (image_edit over a gallery item).
   *
   * It is what turns five loose files into a chain: the gallery collapses the
   * descent into a single tile, and the runtime knows which steps were just
   * rungs toward the result. The origin keeps being read from `source`:
   * 'user' is a user attachment (untouchable), anything else is from the agent.
   */
  parentId?: string
  /** Label given by the script (capture('home')), caption of show_image or
   *  title of the artifact */
  name?: string
  width?: number
  height?: number
  /** Only in artifacts: id of the thumbnail PNG (same folder as the .html), captured
   *  at creation so the gallery keeps being a grid of images. Absent
   *  when the capture failed — the tile falls back to the icon. */
  thumb?: string
  /**
   * Only in LIVE documents in Markdown: the same cover in the dark theme.
   *
   * There are two because the cover is the native screen, and the theme changes after the capture.
   * A document requested as a file does not have one: the white sheet is its face in
   * both themes, because that is how it will come out printed.
   */
  thumbDark?: string
  /** Only in artifacts: increments on every update_artifact. The file is rewritten
   *  in place (the URL does not change), so this is what invalidates the iframe cache. */
  revision?: number
  /** Only in images fetched from the web: author and license (see MediaCredit). */
  credit?: MediaCredit
  /**
   * Only in motion pieces: the id of the composition in the main's registry
   * (`orbit-data/motion.json`). It is through it that the Motion tab reopens the piece — and the
   * ONLY link to the content, since the composition lives in the project folder
   * and nothing of it is copied to the gallery.
   */
  motionId?: string
  /**
   * Only in design canvases: the id of the canvas in the main's registry
   * (`orbit-data/design.json`). Mirrors `motionId` — the folder lives in the
   * app storage (chat mode) and nothing of it is copied to the gallery beyond
   * the cover; opening is reopening the Design tab.
   */
  designId?: string
  /**
   * Only in slides decks: the id of the deck in the main's registry
   * (`orbit-data/slides.json`). Same contract as `designId` and `motionId` — the
   * deck folder is not copied, the record keeps the cover (the first slide) and
   * opening is reopening the Slides tab.
   */
  slidesId?: string
  /**
   * Material of the Sources tab: the sidebar folder this file is
   * SHARED with. Absent = it belongs only to the conversation (`sessionId`). It is the equivalent, for
   * photo, GIF, audio and video, of the `srcN` scope of documents.
   */
  sharedFolderId?: string
  /** Only in videos: the orbit-video:// URL that the gallery viewer plays. */
  videoUrl?: string
  /** Only in videos: duration in ms (the tile label). */
  durationMs?: number
  /** Only in documents: which renderings exist on disk. Empty is the normal
   *  case — the document is born only in Markdown and the file is generated on
   *  the first download. */
  formats?: DocumentFormat[]
  /**
   * Only in documents: the formats that were requested ON PURPOSE — the user
   * said "make a PDF", "send it to me in Word". Absent is the normal case: a
   * live Markdown document, which is read and edited in the conversation.
   *
   * Kept apart from `formats` because the two answer different questions:
   * `formats` is cache and grows on its own when someone downloads the file, and
   * downloading a copy cannot turn the document into a deliverable.
   */
  delivery?: DocumentFormat[]
  /**
   * Only in documents: the conversation source (`doc3`, `src1`) that this document
   * became when the user promoted it. It is what makes promoting idempotent —
   * clicking again focuses what already exists instead of creating a copy.
   *
   * It may point to an already removed source: the id is checked against the list
   * before being used, and promoting again restores what was deleted.
   */
  sourceId?: string
  /**
   * Only in documents: there is a USER edit the agent has not seen yet.
   *
   * Set when the canvas writes, cleared when the agent writes over it
   * knowing about the new version. It is what keeps a blind rewrite from erasing what
   * the person has just typed.
   */
  userEdited?: boolean
  /**
   * Only in documents: the file came from OUTSIDE and has no Markdown source — the
   * edited copy of an attached .docx, the result of merging or cutting PDFs.
   * The `.md` of the record is just a note saying where the real content is.
   *
   * It is what prevents converting those documents on demand: what would be
   * rendered is the preview, not the document.
   */
  derived?: boolean
  /**
   * Only in documents: the chosen customization (font, size, accent
   * color, margin, columns, alignment). Kept here so that
   * update_document keeps the look without the agent having to repeat the style on
   * every text change.
   */
  style?: Record<string, unknown>
  /**
   * Project the asset belongs to — the working folder of the session that
   * created it, captured AT THE MOMENT of creation.
   *
   * The gallery already derived this from the session, but deriving is not enough for two
   * things: the link dies when the session is deleted, and the AGENT has no
   * way of finding what it produced before in the same repository. Written here, the
   * document remains findable by the project even without the conversation.
   */
  directory?: string
  /** Sidebar folder the session was in (chat mode, where there is no
   *  directory) — the equivalent of `directory` for manual grouping. */
  folderId?: string
}

export interface MediaFilter {
  source?: MediaSource | MediaSource[]
  kind?: MediaKind | MediaKind[]
  sessionId?: string
  /** Scope by project: all the assets of that working folder,
   *  regardless of the session that created them. */
  directory?: string
  folderId?: string
  /** createdAt >= since */
  since?: number
  /** Search (case-insensitive) in name/taskId/id */
  query?: string
}

